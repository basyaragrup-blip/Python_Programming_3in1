locations = ["Jepang", "New Zeeland", "Jerman", "Rusia", "Perancis"]
print("Urutan asli:")
print(locations)
print("\nsorted() alfabetis (list asli tidak berubah):")
print(sorted(locations))
print("\nList asli masih sama:")
print(locations)
print("\nsorted() alfabetis terbalik (list asli tidak berubah):")
print(sorted(locations, reverse=True))
print("\nList asli masih sama:")
print(locations)
locations.reverse()
print("\nSetelah reverse():")
print(locations)
locations.reverse()
print("\nSetelah reverse() lagi (kembali ke asli):")
print(locations)
locations.sort()
print("\nSetelah sort():")
print(locations)
locations.sort(reverse=True)
print("\nSetelah sort(reverse=True):")
print(locations)